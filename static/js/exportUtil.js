/**
 * Export Utility - Formats redline reports for HTML download, Clipboard, and PDF Print
 */

class ExportUtil {

  /**
   * Download standalone HTML document report
   */
  exportStandaloneHTML(comparisonData) {
    const stats = comparisonData.statistics || {};
    const htmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>PDF Redline Report - ${new Date().toLocaleDateString()}</title>
  <style>
    body { font-family: 'Times New Roman', Georgia, serif; font-size: 16px; line-height: 1.8; color: #111827; padding: 40px; max-width: 900px; margin: 0 auto; }
    h1 { font-family: Arial, sans-serif; font-size: 24px; color: #1E3A8A; border-bottom: 2px solid #E5E7EB; padding-bottom: 10px; margin-bottom: 20px; }
    .stats-bar { display: flex; gap: 20px; font-family: Arial, sans-serif; background: #F3F4F6; padding: 12px 20px; border-radius: 8px; margin-bottom: 30px; font-size: 14px; }
    .stat-item { font-weight: bold; }
    .stat-ins { color: #059669; }
    .stat-del { color: #DC2626; }
    ins.diff-ins { background-color: #D1FAE5; color: #065F46; text-decoration: underline; font-weight: bold; padding: 1px 3px; border-radius: 3px; }
    del.diff-del { background-color: #FEE2E2; color: #991B1B; text-decoration: line-through; font-weight: bold; padding: 1px 3px; border-radius: 3px; }
    .footer { margin-top: 50px; font-size: 12px; color: #6B7280; font-family: Arial, sans-serif; border-top: 1px solid #E5E7EB; padding-top: 15px; }
  </style>
</head>
<body>
  <h1>PDF Redline Tracked Changes Report</h1>
  <div class="stats-bar">
    <div class="stat-item">Similarity: ${stats.similarity_score || '--'}%</div>
    <div class="stat-item stat-ins">Additions: +${stats.additions_words || 0} words</div>
    <div class="stat-item stat-del">Deletions: -${stats.deletions_words || 0} words</div>
    <div class="stat-item">Total Diffs: ${stats.changes_count || 0}</div>
  </div>
  <div class="redline-body">
    ${comparisonData.redlineHtml || ''}
  </div>
  <div class="footer">
    Generated by RedlinePDF PRO Suite on ${new Date().toLocaleString()}
  </div>
</body>
</html>`;

    const blob = new Blob([htmlContent], { type: "text/html" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `Redline_Report_${Date.now()}.html`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  /**
   * Copy plaintext redline format to clipboard
   */
  async copyPlaintextRedline(comparisonData) {
    if (!comparisonData.diffs) return;

    let textBuffer = "";
    comparisonData.diffs.forEach(t => {
      if (t.op === "EQUAL") textBuffer += t.text;
      else if (t.op === "INSERT") textBuffer += `[+ ${t.text} +]`;
      else if (t.op === "DELETE") textBuffer += `[- ${t.text} -]`;
    });

    await navigator.clipboard.writeText(textBuffer);
  }

  /**
   * Render the formatted redline (independent of whatever is currently on
   * screen) into a hidden light-theme container, rasterize it with
   * html2canvas, and slice that image into letter-size PDF pages ourselves.
   * This is more reliable than jsPDF's built-in .html()/autoPaging, which
   * reads element coordinates via getBoundingClientRect() and produces a
   * blank PDF if the source element isn't positioned in-flow near the
   * viewport origin. The container renders at a low z-index behind the
   * app's own full-screen loading overlay (shown by the caller during
   * export), so nothing is visibly seen on screen. Trade-off: the resulting
   * PDF is an image of the redline, not selectable text — a print-quality
   * vector export would require a server-side renderer, which this
   * browser-only tool intentionally doesn't have.
   */
  async exportRedlinePDF(comparisonData) {
    if (!comparisonData) return;

    if (!window.jspdf || !window.html2canvas) {
      alert("PDF export library failed to load (check your internet connection) — try the Standalone HTML export instead.");
      return;
    }

    const { jsPDF } = window.jspdf;

    const container = document.createElement("div");
    container.className = "pdf-export-render";
    container.style.cssText = "position:fixed; top:0; left:0; width:700px; z-index:1; padding:28px; background:#FFFFFF;";
    container.innerHTML = `
      <h1>PDF Redline Tracked Changes Report</h1>
      <div>${comparisonData.redlineHtml || "<p>No differences found.</p>"}</div>
    `;
    document.body.appendChild(container);

    try {
      // Let the browser paint the container before capturing it. A fixed
      // timeout (not requestAnimationFrame) is used deliberately: rAF can be
      // throttled or never fire at all for a backgrounded/inactive tab,
      // which would hang this export indefinitely.
      await new Promise(resolve => setTimeout(resolve, 50));

      const canvas = await window.html2canvas(container, {
        scale: 2,
        backgroundColor: "#FFFFFF",
        windowWidth: container.scrollWidth,
        windowHeight: container.scrollHeight
      });

      if (canvas.width === 0 || canvas.height === 0) {
        throw new Error("Rendered content was empty.");
      }

      const pdf = new jsPDF({ unit: "pt", format: "letter" });
      const pageWidth = pdf.internal.pageSize.getWidth();
      const pageHeight = pdf.internal.pageSize.getHeight();
      const margin = 30;
      const usableWidthPt = pageWidth - margin * 2;
      const usableHeightPt = pageHeight - margin * 2;

      const ptPerSourcePx = usableWidthPt / canvas.width;
      const pageHeightPx = usableHeightPt / ptPerSourcePx;

      let renderedPx = 0;
      let pageIndex = 0;

      while (renderedPx < canvas.height) {
        const sliceHeightPx = Math.min(pageHeightPx, canvas.height - renderedPx);

        const pageCanvas = document.createElement("canvas");
        pageCanvas.width = canvas.width;
        pageCanvas.height = sliceHeightPx;
        pageCanvas.getContext("2d").drawImage(
          canvas,
          0, renderedPx, canvas.width, sliceHeightPx,
          0, 0, canvas.width, sliceHeightPx
        );

        const imgData = pageCanvas.toDataURL("image/jpeg", 0.92);
        if (pageIndex > 0) pdf.addPage();
        pdf.addImage(imgData, "JPEG", margin, margin, usableWidthPt, sliceHeightPx * ptPerSourcePx);

        renderedPx += sliceHeightPx;
        pageIndex++;
      }

      pdf.save(`Redline_Report_${Date.now()}.pdf`);
    } finally {
      document.body.removeChild(container);
    }
  }
}

window.exportUtil = new ExportUtil();
